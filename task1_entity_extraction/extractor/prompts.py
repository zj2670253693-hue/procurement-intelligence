BASE_QUANTITY_RULE = """数量证据规则：quantity必须对应当前标的或采购包的明确采购数量，证据可以是“数量/采购数量/计量数量”等列，或正文明确的采购数量表述；保留原文明示的数值和单位，不从金额、单价、预算或明细数量自行计算。
禁止默认填“1项”“1套”“1个”：只有一个项目、一个采购包、一行服务或一个产品名称，不代表采购数量为1。原文明示的数量必须保留，例如明确数量为1项时仍填“1项”，不能因为值为1就一律删除。
序号、品目号、包号、条款编号中的数字或“项”不是采购数量。服务时间、服务期限和服务范围中的人数、点位数仅说明期限或覆盖范围，不能自动转成采购数量；只有原文明确把人数或年数标为当前标的的采购数量时，才按该数量表述保留，不推算、不替换其他字段。
同名标的在多个采购包出现时，数量证据须结合包号、对应标的和供应商等信息判断归属，不能按结果行顺序配包或借用其他包的数量；不能唯一对应时数量留空字符串。输入中未提供数量、只写“详见附件/采购文件”、或存在未读取的附件，都不能靠猜测补数量，也不能由附件缺失推断数量为1。
"""


BASE_GRANULARITY_RULE = """基础层粒度规则（与附件详细清单区分）：
1. 先检查HTML公告正文的“主要标的信息”及其表格。逐项列出的真实标的应逐项保留，不能因属于同一个项目或同一供应商就合并。招标需求、表单范本和未中标报价不是新增成交标的的依据。
2. 当HTML主标的表只给出采购包名称，其品牌、型号、单价、数量均指向附件时，基础结果保留采购包行，不得展开附件设备清单来替代采购包行。包级品牌填写该包明确的中标供应商，不能借用附件中的某个设备品牌代表整包；包级总价只填该包明确成交金额。附件逐项设备清单属于单独的详细展示层。
3. 分档计价是例外：原文对同一服务明确列出不同人员级别、服务种类或计量口径及各自费率时，每个计价档位分别输出，并保留该档位所属包号、供应商和原文明示的档位标识。不要把多个档位的费率合并进一条unit_price。明确的计价档位标识可以保留在产品服务名称和对应规格说明中；一般服务范围、履约描述或单纯并列词不能据此拆行。
   分档计价优先于“一个采购包一行”：中标（成交）信息中的明确分档报价也是成交标的证据，不能因“主要标的信息”未重复列出档位而忽略。先逐一核对每个中标供应商的费率列表，再为每个明确档位生成独立记录；输出的每个unit_price只含该档位的一项费率。为区分同名标的或跨包同档同价记录，产品服务名称中保留原文明示的包号，分档名称使用“服务名称+包号+档位”；未明示包号时仍用服务名称加档位，不自行编号，不能按结果行顺序猜包。与费率绑定的人员资格档位属于该行明确规格，不是一般履约说明；包号不能当作规格型号。不新增package_name字段，也不因补包号猜测其他字段。
   通用示例（数值仅示范，不得套用到实际公告）：第1包咨询服务，中标供应商甲公司，资深人员800元/人/天、一般人员400元/人/天，应输出两行：{"product_name":"咨询服务（第1包，资深人员）","brand":"甲公司","spec_model":"资深人员","unit_price":"800元/人/天"}和{"product_name":"咨询服务（第1包，一般人员）","brand":"甲公司","spec_model":"一般人员","unit_price":"400元/人/天"}；其余字段有原文证据才填。若第2包也是甲公司且资深人员同为800元/人/天，其独立记录名称仍为“咨询服务（第2包，资深人员）”，不得与第1包去重合并。不能输出一行“资深人员800；一般人员400”。多个采购包均有分档时，对每个包分别这样展开，不能只处理第一个包。
4. 缺少逐项清单但正文已明确采购项目/服务名称、中标单位和成交事实时，可以按明确的采购对象保留项目或采购包级记录；附件缺失也不应返回空实体。未明确的字段仍为空，不猜品牌、型号或数量，不把预算、未中标报价当成交金额。
"""


OFFICIAL_QA_RULE = """官方补充口径（2026-10-09至10-11）：
只提取实际中标/成交的标的。招标文件、采购需求、预算清单和投标报价/范本不是实际中标清单；不能仅凭文件名判断，应核对具体章节、表格字段与成交证据。中标明细、中标一览及公示中明示的实际标的才是成交依据。废标、流标、终止或未成交包不混入基础结果，需求信息和未成交信息仅作独立备注。
项目/采购包归口金额以公示的项目/包成交金额为准；产品行总价以该产品原文明示总价为先。未明示产品总价时，仅当同一实际中标行的单价、采购数量、货币与计量口径明确且归属唯一，才可用单价×数量计算产品总价。税费、服务费等可能使产品金额之和不等于公示项目金额，不需要强行配平。
严禁把项目/包金额直接复制给单个产品；只有一个已公示产品也不证明它等于全包成交金额。不能用包总额减去某产品金额推造剩余产品价格，不能由预算×折扣率、服务期限或范围人数反推成交价/数量。无明确值且没有强逻辑关系的，统一输出空字符串。
采购包/标的与供应商无法明确映射时，按主项目保留来源中的各条独立供应商+成交金额记录；不按表格/结果行顺序猜包，不靠相同金额确定归属。没有产品级对应证据的品牌、规格、单价、数量留空。同供应商同金额的不同来源成交记录不能仅凭七字段相同就合并；也不能把正文与表格的同一记录重复输出。行顺序没有硬性评分要求。
"""


